export type EntityCategory = 'country' | 'state' | 'city' | 'brand' | 'company' | 'car' | 'celebrity' | 'event';
export type Entity = { id: string; name: string; category: EntityCategory; date: string; note: string };

export const slugify = (s: string): string =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const group = (category: EntityCategory, rows: [string, string, string][]): Entity[] =>
  rows.map(([name, date, note]) => ({ id: slugify(name), name, category, date, note }));

